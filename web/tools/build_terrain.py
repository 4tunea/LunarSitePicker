"""Make the coarse terrain grid the browser uses for picked spots.

    python web/tools/build_terrain.py        (needs numpy and data/LDEM_75S_120M.IMG)

Block-averages NASA's LOLA LDEM_75S_120M (75-90 deg S, 120 m) by FACTOR, quantises heights
to QUANT metres, delta-codes and deflates them, and writes web/data/terrain-lowres.js.
The analysed sites do NOT use this grid; they use the horizons in the navigator data file.
"""
import base64, os, zlib
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "data", "LDEM_75S_120M.IMG")
OUT = os.path.join(ROOT, "web", "data", "terrain-lowres.js")
FACTOR, QUANT, N_SRC, PX_SRC = 6, 2, 7624, 120.00684643669544

a = np.memmap(SRC, dtype="<i2", mode="r", shape=(N_SRC, N_SRC))
n = N_SRC // FACTOR
crop = (N_SRC - n * FACTOR) // 2
block = a[crop:crop + n * FACTOR, crop:crop + n * FACTOR].astype(np.float32) * 0.5      # metres
low = block.reshape(n, FACTOR, n, FACTOR).mean(axis=(1, 3))
q = np.round(low / QUANT).astype(np.int32).ravel()
deltas = np.diff(q, prepend=0)
assert np.abs(deltas).max() < 32767
payload = base64.b64encode(zlib.compress(deltas.astype("<i2").tobytes(), 9)).decode("ascii")
with open(OUT, "w") as f:
    f.write("/* Coarse south-pole terrain for picked spots. Generated by web/tools/build_terrain.py from\n"
            "   NASA LOLA LDEM_75S_120M (block mean x%d). Do not edit by hand. */\n" % FACTOR)
    f.write('var TERRAIN_LOWRES = {"n":%d,"px_m":%.3f,"quant_m":%d,"edge_lat_deg":-75,'
            '"source":"LOLA LDEM_75S_120M, block mean to %d m","deflate_b64":"%s"};\n'
            % (n, PX_SRC * FACTOR, QUANT, round(PX_SRC * FACTOR), payload))
print("wrote %s: %d x %d px, %.0f m per pixel, %.1f MB" % (os.path.relpath(OUT, ROOT), n, n, PX_SRC * FACTOR, os.path.getsize(OUT) / 1e6))
